#!/bin/sh
# Writes the CORS allowlist for the Supabase gateway (runs from /docker-entrypoint.d before nginx starts).
#
# SUPABASE_CORS_ORIGINS is a comma-separated list of exact origins (scheme://host[:port]); compose
# defaults it to SUPABASE_SITE_URL. Browsers on any other origin get no Access-Control-Allow-Origin, so
# other websites cannot drive sign-up, recovery or OTP endpoints from their visitors' browsers.
set -eu

out="${JT_CORS_MAP_FILE:-/etc/nginx/conf.d/00-jt-cors.conf}"
tmp="${out}.tmp"
{
  echo '# Generated by 15-jt-cors-map.sh from SUPABASE_CORS_ORIGINS.'
  echo 'map $http_origin $jt_cors_origin {'
  echo '    default "";'
  old_ifs=$IFS
  IFS=','
  for origin in ${SUPABASE_CORS_ORIGINS:-}; do
    origin=$(printf '%s' "$origin" | tr -d ' ')
    origin=${origin%/}
    case "$origin" in
      "") ;;
      *[!A-Za-z0-9.:/-]*) echo "jt-code gateway: ignoring invalid CORS origin" >&2 ;;
      http://?*|https://?*) printf '    "%s" "%s";\n' "$origin" "$origin" ;;
      *) echo "jt-code gateway: ignoring CORS origin without http(s) scheme" >&2 ;;
    esac
  done
  IFS=$old_ifs
  echo '}'
} > "$tmp"
mv "$tmp" "$out"
